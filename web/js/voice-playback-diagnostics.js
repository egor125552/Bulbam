export function explainVoicePlaybackError(code) {
  switch (Number(code)) {
    case 1: return "Воспроизведение было прервано.";
    case 2: return "Не удалось загрузить звук по сети. Проверьте соединение и повторите воспроизведение.";
    case 3: return "Браузер не смог декодировать голосовое. Возможно, запись повреждена.";
    case 4: return "Формат этого голосового не поддерживается браузером.";
    default: return "Не удалось воспроизвести голосовое сообщение.";
  }
}
